#!/usr/bin/env node

/**
 * SmartHotel Demo Environment Setup Script
 * 
 * This script helps set up environment variables for demo/development use.
 * Run: node scripts/setup-demo-env.js
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const envFilePath = path.join(process.cwd(), '.env.local');
const exampleFilePath = path.join(process.cwd(), '.env.example');

// Generate a secure random secret
function generateSecret(length = 32) {
  return crypto.randomBytes(length).toString('base64');
}

// Demo environment template
const demoEnvTemplate = `# ===========================================
# SmartHotel Environment Variables (Demo/Development)
# Generated by setup-demo-env.js
# ===========================================

# ===========================================
# Database Configuration
# ===========================================
# MongoDB connection string
# For demo: Use MongoDB Atlas free tier (https://www.mongodb.com/cloud/atlas)
# Or local MongoDB: mongodb://localhost:27017/smarthotel
DATABASE_URL=mongodb://localhost:27017/smarthotel

# ===========================================
# NextAuth Configuration
# ===========================================
NEXTAUTH_URL=http://localhost:3000
NEXTAUTH_SECRET=${generateSecret(32)}

# ===========================================
# Stripe Payment Configuration
# ===========================================
# Get test keys from: https://dashboard.stripe.com/test/apikeys
# These are TEST MODE keys (for development only)
STRIPE_SECRET_KEY=sk_test_YOUR_STRIPE_SECRET_KEY_HERE
STRIPE_PUBLISHABLE_KEY=pk_test_YOUR_STRIPE_PUBLISHABLE_KEY_HERE
STRIPE_WEBHOOK_SECRET=whsec_YOUR_WEBHOOK_SECRET_HERE

# ===========================================
# Email Configuration (SMTP)
# ===========================================
# Option 1: Mailtrap (Recommended for testing)
# Sign up at: https://mailtrap.io (free tier available)
SMTP_HOST=sandbox.smtp.mailtrap.io
SMTP_PORT=2525
SMTP_USER=YOUR_MAILTRAP_USERNAME
SMTP_PASS=YOUR_MAILTRAP_PASSWORD
SMTP_FROM_EMAIL=noreply@smarthotel.com
SMTP_FROM_NAME=SmartHotel

# Option 2: Gmail (for demo/testing)
# Uncomment and use if you prefer Gmail:
# SMTP_HOST=smtp.gmail.com
# SMTP_PORT=587
# SMTP_USER=your-email@gmail.com
# SMTP_PASS=your-app-specific-password

# ===========================================
# Socket.IO Configuration (Optional)
# ===========================================
SOCKET_IO_URL=http://localhost:3000

# ===========================================
# Application Configuration
# ===========================================
NODE_ENV=development
`;

const exampleEnvTemplate = `# ===========================================
# SmartHotel Environment Variables Template
# ===========================================
# Copy this file to .env.local and update with your values

# Database Configuration
DATABASE_URL=your-mongodb-connection-string

# NextAuth Configuration
NEXTAUTH_URL=http://localhost:3000
NEXTAUTH_SECRET=generate-with-openssl-rand-base64-32

# Stripe Payment Configuration (Test Mode)
STRIPE_SECRET_KEY=sk_test_your_stripe_secret_key
STRIPE_PUBLISHABLE_KEY=pk_test_your_stripe_publishable_key
STRIPE_WEBHOOK_SECRET=whsec_your_webhook_secret

# Email Configuration (SMTP)
SMTP_HOST=sandbox.smtp.mailtrap.io
SMTP_PORT=2525
SMTP_USER=your-smtp-username
SMTP_PASS=your-smtp-password
SMTP_FROM_EMAIL=noreply@smarthotel.com
SMTP_FROM_NAME=SmartHotel

# Socket.IO Configuration
SOCKET_IO_URL=http://localhost:3000

# Application Configuration
NODE_ENV=development
`;

function setupDemoEnv() {
  console.log('🚀 SmartHotel Demo Environment Setup\n');
  
  // Create .env.example if it doesn't exist
  if (!fs.existsSync(exampleFilePath)) {
    fs.writeFileSync(exampleFilePath, exampleEnvTemplate);
    console.log('✅ Created .env.example template');
  } else {
    console.log('ℹ️  .env.example already exists');
  }
  
  // Check if .env.local already exists
  if (fs.existsSync(envFilePath)) {
    console.log('\n⚠️  .env.local already exists!');
    console.log('   To create a new demo environment:');
    console.log(`   1. Back up your current .env.local`);
    console.log(`   2. Delete .env.local`);
    console.log(`   3. Run this script again`);
    console.log('\n   Or manually update .env.local with the required variables.');
    return;
  }
  
  // Create .env.local with demo values
  fs.writeFileSync(envFilePath, demoEnvTemplate);
  
  console.log('✅ Created .env.local with demo values');
  console.log('\n📝 Next Steps:');
  console.log('\n1. Database Setup:');
  console.log('   - Sign up for MongoDB Atlas free tier: https://www.mongodb.com/cloud/atlas');
  console.log('   - Or install local MongoDB');
  console.log('   - Update DATABASE_URL in .env.local');
  
  console.log('\n2. Stripe Setup (for payments):');
  console.log('   - Get test keys: https://dashboard.stripe.com/test/apikeys');
  console.log('   - Update STRIPE_SECRET_KEY and STRIPE_PUBLISHABLE_KEY in .env.local');
  
  console.log('\n3. Email Setup (for notifications):');
  console.log('   - Option A: Sign up for Mailtrap (free): https://mailtrap.io');
  console.log('     Update SMTP_USER and SMTP_PASS in .env.local');
  console.log('   - Option B: Use Gmail with app-specific password');
  console.log('     Update SMTP_HOST, SMTP_USER, SMTP_PASS in .env.local');
  
  console.log('\n4. Security:');
  console.log('   - NEXTAUTH_SECRET has been auto-generated');
  console.log('   - Keep your .env.local file secure and never commit it to git');
  
  console.log('\n✨ Demo environment ready! Run: npm run dev');
}

// Run the setup
setupDemoEnv();







